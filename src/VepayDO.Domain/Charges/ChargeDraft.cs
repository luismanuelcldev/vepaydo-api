using VepayDO.Domain.Common;
using VepayDO.Domain.Enums;

namespace VepayDO.Domain.Charges;

/// <summary>
/// A charge ready to be persisted, used as the <b>Prototype</b> for
/// "duplicate charge" (UC-DATA-04, AGENTS.md section 8.4). <see cref="Clone"/>
/// returns a new, fully independent draft: a fresh identity, a cleared
/// <see cref="Status"/> (<c>OPEN</c>) and no <see cref="Allocations"/>, while the
/// descriptive fields (code, description, amount, dates) are copied deeply so the
/// copy never shares mutable state with the original.
/// </summary>
public sealed record ChargeDraft : ICloneable<ChargeDraft>
{
    public ChargeDraft(
        Guid? id,
        Guid? customerId,
        ChargeCode code,
        string description,
        Money amount,
        DateOnly issuedOn,
        DateOnly? dueOn,
        ChargeStatus status,
        Guid? createdBy,
        IReadOnlyList<ChargeAllocationDraft> allocations)
    {
        Id = id;
        CustomerId = customerId;
        Code = code;
        Description = description;
        Amount = amount;
        IssuedOn = issuedOn;
        DueOn = dueOn;
        Status = status;
        CreatedBy = createdBy;
        Allocations = allocations;
    }

    public Guid? Id { get; init; }

    public Guid? CustomerId { get; init; }

    public ChargeCode Code { get; init; }

    public string Description { get; init; }

    public Money Amount { get; init; }

    public DateOnly IssuedOn { get; init; }

    public DateOnly? DueOn { get; init; }

    public ChargeStatus Status { get; init; }

    public Guid? CreatedBy { get; init; }

    public IReadOnlyList<ChargeAllocationDraft> Allocations { get; init; }

    /// <summary>
    /// Builds the duplicate: a new draft with no identity, <c>OPEN</c> status and
    /// no allocations. The code must be regenerated by the caller (a new unique
    /// code is needed), so it is carried through unchanged and reassigned upstream.
    /// Implemented explicitly because <c>record</c> already synthesizes a
    /// <c>Clone</c> member (the compiler copy) that would otherwise mask the
    /// Prototype contract (see AGENTS.md section 8.4).
    /// </summary>
    ChargeDraft ICloneable<ChargeDraft>.Clone() =>
        new(
            id: null,
            customerId: CustomerId,
            code: Code,
            description: Description,
            amount: new Money(Amount.Amount, Amount.Currency),
            issuedOn: IssuedOn,
            dueOn: DueOn,
            status: ChargeStatus.OPEN,
            createdBy: CreatedBy,
            allocations: []);

    /// <summary>Creates a blank draft with the invariants already applied.</summary>
    public static ChargeDraft Create(
        Guid? customerId,
        ChargeCode code,
        string description,
        Money amount,
        DateOnly issuedOn,
        DateOnly? dueOn,
        Guid? createdBy) =>
        new(
            id: null,
            customerId: customerId,
            code: code,
            description: description,
            amount: new Money(amount.Amount, amount.Currency),
            issuedOn: issuedOn,
            dueOn: dueOn,
            status: ChargeStatus.OPEN,
            createdBy: createdBy,
            allocations: []);
}

/// <summary>A single allocation attached to a charge draft (used by the duplicate rules).</summary>
public sealed record ChargeAllocationDraft(Guid ReceiptId, Money AmountApplied);
